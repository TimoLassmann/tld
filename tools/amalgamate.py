"""Build the single-header tld.h from the module sources in src/.

    uv run python tools/amalgamate.py           # write ./tld.h
    uv run python tools/amalgamate.py --check   # exit 1 if ./tld.h is out of date

The declaration half is src/tld.h with every local header inlined (each once). The
implementation half is src/tld.c with every local .c inlined, wrapped in
#ifdef TLD_IMPLEMENTATION. src/ stays the source of truth; never edit ./tld.h by hand.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = ROOT / "tld.h"
INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"')

TOP = """\
/* tld.h - single-header C toolbox (allocation and error macros, strings, hash map, JSON,
 * rng, statistics, sorting, k-d tree, thread pool, templates, file helpers).
 *
 * GENERATED by tools/amalgamate.py from src/ - do not edit; change src/ and regenerate.
 *
 * Usage: in exactly one .c file of your program
 *
 *     #define TLD_IMPLEMENTATION
 *     #include "tld.h"
 *
 * and plain #include "tld.h" everywhere else. Link with -lm -lpthread.
 *
 * Licence: MIT, see the end of this file.
 */
"""

