"""Build the single-header tld.h from the module sources in src/.

    uv run python tools/amalgamate.py           # write ./tld.h
    uv run python tools/amalgamate.py --check   # exit 1 if ./tld.h is out of date

The declaration half is src/tld.h with every local header inlined (each once). The
implementation half is src/tld.c with every local .c inlined, wrapped in
#ifdef TLD_IMPLEMENTATION. src/ stays the source of truth; never edit ./tld.h by hand.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = ROOT / "tld.h"
INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"')

TOP = """\
/* tld.h - single-header C toolbox: allocation and error macros, terminal messages,
 * strings, a hash map, JSON, random numbers, statistics, sorting, a k-d tree, a thread
 * pool, text templates and file helpers.
 *
 * tld.h is GENERATED by tools/amalgamate.py from src/: do not edit it; change src/ and
 * regenerate. Manual: docs/tld.md, generated from tld.h by tools/tlddoc.c.
 *
 * USAGE
 *   In exactly one .c file of your program, before any other #include:
 *
 *       #define TLD_IMPLEMENTATION
 *       #include "tld.h"
 *
 *   and plain #include "tld.h" everywhere else. C11 plus POSIX (pthreads, stat,
 *   realpath); macOS and Linux. Build: cc -std=c11 prog.c -lm -lpthread.
 *
 * ERRORS
 *   A function that can fail returns int: OK (0) on success, FAIL (1) on failure, with
 *   its results in pointer arguments; one that returns a pointer returns NULL on
 *   failure. Failures print an ERROR line (time, message, file and line) to stderr;
 *   lookups that just find nothing (tld_hash_get, tld_json_get_*, ...) return FAIL
 *   silently. Yes/no questions (tld_path_exists, tld_path_is_dir, tld_nearly_equal_*,
 *   tld_term_has_color) return 1 or 0, and a few functions return a plain value; each
 *   one says so. Nothing exits or aborts.
 *
 *   RUN(call), ASSERT(test, fmt, ...), ERROR_MSG(fmt, ...) and the allocation macros
 *   MMALLOC, MREALLOC, MMALLOC_ALIGNED and galloc jump to a label named ERROR in the
 *   calling function on failure. The usual shape of a function:
 *
 *       int load(const char *path, tld_strbuf **out)
 *       {
 *               tld_strbuf *b = NULL;
 *               ASSERT(path != NULL, "No path");
 *               RUN(tld_strbuf_alloc(&b, 256));
 *               RUN(tld_strbuf_append(b, path));
 *               *out = b;
 *               return OK;
 *       ERROR:
 *               tld_strbuf_free(b);
 *               return FAIL;
 *       }
 *
 *   Initialise every pointer to NULL: MMALLOC refuses a non-NULL pointer, and the
 *   cleanup after ERROR: may run before an allocation happened.
 *
 *   LOG_MSG, WARNING_MSG, ERROR_MSG, ASSERT and the rich-output calls take a printf
 *   format, checked by the compiler. Print text from users or files with "%s", never as
 *   the format itself: LOG_MSG("%s", line), not LOG_MSG(line).
 *
 * MEMORY
 *   Objects come from an allocator (tld_strbuf_alloc(&b, ...), tld_hash_alloc,
 *   tld_tld_kdtree_alloc, tld_rng_alloc, tld_json_parse, TLD_JSON_OBJECT, ...) and belong to the caller,
 *   who frees them with the matching free function (tld_strbuf_free, tld_hash_free,
 *   tld_tld_kdtree_free, tld_rng_free, tld_json_obj_free, ...); every free function accepts NULL.
 *   galloc memory is freed with gfree, MMALLOC memory with MFREE, never with free();
 *   both set the pointer to NULL, so freeing again on an error path is harmless.
 *   Pointers handed out by an object (tld_hash_get, tld_json_get_str, ...) are borrowed
 *   and const: valid until that object changes or is freed; never write through them
 *   or free them. Sizes are int-based: a string buffer holds at most INT32_MAX - 1 bytes
 *   and refuses to grow past that.
 *
 * THREADS
 *   Objects have no locks: use each one from one thread at a time. The tld_thread_pool_*
 *   calls and tld_logsum_init are thread-safe; tld_progress and the TLD_START_TIMER timer keep
 *   global state.
 *
 * ENVIRONMENT
 *   TLD_VERBOSE  0 errors only, 1 normal (default), 2 also DEBUG_MSG lines
 *   NO_COLOR     set and non-empty: no colour on stderr (likewise TERM=dumb)
 *
 * LIMITATIONS
 *   JSON integers that fit in 32 bits are stored exactly; larger ones are stored as
 *   double, exact only up to 2^53 (9007199254740992), so bigger values lose precision.
 *   JSON parsing is strict (RFC 8259): True, NaN, leading zeros and trailing commas are
 *   rejected. JSON keys containing '.' or '[' cannot be addressed by path.
 *   tld_progress keeps one bar at a time and is not for concurrent use from threads.
 *   POSIX only (macOS, Linux, other Unix); not Windows except through WSL.
 *
 * LICENCE: MIT, see the end of tld.h.
 */
"""

